def mechanism_copy(text, base_notice, *, extra_detail_headings=()):
    body, notes = [], []
    in_details = False
    for line in text.splitlines():
        if line.startswith('【'):
            in_details = line in DETAIL_HEADINGS or line in extra_detail_headings
        if in_details:
            notes.append(line)
        elif line == base_notice:
            continue
        elif line in SHORT_LINES:
            notes.append(line)
            if SHORT_LINES[line]:
                body.append(SHORT_LINES[line])
        else:
            body.append(line)
    return '\n'.join(body).strip(), '\n'.join(notes).strip()
